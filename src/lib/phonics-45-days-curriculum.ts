import type { PhonicsDayData, PhonicsWordItem } from './phonics-45-days-units';

type CompactWordTuple = [
  word: string,
  onset: string,
  rime: string,
  ipa: string,
  meaningVi: string,
  exampleSentence: string
];

interface CompactDaySpec {
  day: number;
  stage: number;
  stageTitle: string;
  title: string;
  rime: string;
  vowel: 'a' | 'e' | 'i' | 'o' | 'u';
  words: CompactWordTuple[];
  storyTitle: string;
  storyLines: [string, string, string, string];
  quizQuestion: string;
  quizOptions: [string, string, string, string];
  quizCorrectAnswer: string;
  quizExplanationEn: string;
  quizExplanationVi: string;
}

function toDayData(spec: CompactDaySpec): PhonicsDayData {
  const words: PhonicsWordItem[] = spec.words.map(
    ([word, onset, rime, ipa, meaningVi, exampleSentence]) => ({
      word,
      onset,
      rime,
      ipa,
      meaningVi,
      exampleSentence,
      audioText: word,
    })
  );

  return {
    day: spec.day,
    stage: spec.stage,
    stageTitle: spec.stageTitle,
    title: spec.title,
    rime: spec.rime,
    vowel: spec.vowel,
    words,
    decodableStory: {
      title: spec.storyTitle,
      lines: spec.storyLines,
      comprehensionQuestion: {
        question: spec.quizQuestion,
        options: spec.quizOptions,
        correctAnswer: spec.quizCorrectAnswer,
        explanation: `[EN] ${spec.quizExplanationEn} | [VI] ${spec.quizExplanationVi}`,
      },
    },
  };
}

